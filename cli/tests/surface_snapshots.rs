//! The user-visible surface of the build this repository ships, frozen as
//! committed snapshots (S-639, CR-213, [FR-DS-04], [FR-DS-05]).
//!
//! CR-213 moved chat and the wiki behind an extension host without changing what
//! any shipped binary exposed; CR-214 then took both out of this repository, so
//! the build it ships composes no extension. These snapshots freeze that surface,
//! and every later change must keep them equal:
//!
//! - the composed web route census and the `POST` allow-list;
//! - MCP `tools/list` — names, descriptions and input schemas, single-root and
//!   federated;
//! - `logos --help`;
//! - the config read-model JSON (`GET /api/v1/config`).
//!
//! The SPA navigation snapshot lives beside the registry it reads, in
//! `web/ui/src/nav.snapshot.test.ts`.
//!
//! Every surface is read **composed** — through the extension host the `main`
//! hands the library ([`public_host`]) — so an extension registered there would be
//! read by every snapshot. This file compiles to nothing in a build without `ui`:
//! the slim build has no web surface. `no_extension_surface.rs` holds the same
//! build to the rule that nothing on it names chat or the wiki, through the same
//! readers (`support/surface.rs`).
//!
//! # These are a baseline, not a convenience
//!
//! A snapshot that could be regenerated by a flag would let a surface change
//! re-bless itself, so there is no refresh mode: `LOGOS_WRITE_SURFACE_SNAPSHOTS=1`
//! writes a snapshot **only where none exists**, and an existing one is changed
//! only by deleting it in a reviewed commit. The files under `default/` were last
//! regenerated when chat and the wiki left this repository (S-651): the earlier
//! default-build snapshots less exactly their chat and wiki entries.
//!
//! [FR-DS-04]: ../../docs/specs/requirements/FR-DS-04.md
//! [FR-DS-05]: ../../docs/specs/requirements/FR-DS-05.md

#![cfg(feature = "ui")]

use std::path::{Path, PathBuf};

use axum::http::StatusCode;
use logos_ext::ExtensionHost;

/// The build these snapshots describe: the default one, the build this
/// repository ships.
const FLAVOR: &str = "default";

/// The surface readers this suite shares with `no_extension_surface.rs`.
#[path = "support/surface.rs"]
mod surface;
use surface::{
    composed_web_surface, configured_project, get_json, help, mcp_rosters, pretty, render_census,
    RouteEntry,
};

/// The binary's composition, compiled from the file `main` composes
/// from — so these snapshots read the binary's own host, never a copy of it.
#[path = "../src/composition.rs"]
mod composition;

/// The host the binary composes ([`composition::host`]).
fn public_host() -> ExtensionHost {
    composition::host()
}

// ── Snapshot comparison ────────────────────────────────────────────────────

fn snapshot_path(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/surface_snapshots")
        .join(FLAVOR)
        .join(name)
}

/// Compare `actual` with the committed snapshot `name`, failing on the first
/// differing line. A missing snapshot is written only when
/// `LOGOS_WRITE_SURFACE_SNAPSHOTS` is set; an existing one is never rewritten.
fn assert_snapshot(name: &str, actual: &str) {
    let path = snapshot_path(name);
    let expected = match std::fs::read_to_string(&path) {
        Ok(expected) => expected,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            if std::env::var_os("LOGOS_WRITE_SURFACE_SNAPSHOTS").is_some() {
                std::fs::create_dir_all(path.parent().expect("a snapshot directory"))
                    .expect("create the snapshot directory");
                std::fs::write(&path, actual).expect("write the new snapshot");
                return;
            }
            panic!(
                "no committed snapshot at {}: set LOGOS_WRITE_SURFACE_SNAPSHOTS=1 to create a \
                 NEW one (it never overwrites)",
                path.display()
            );
        }
        Err(e) => panic!("reading {}: {e}", path.display()),
    };
    if expected == actual {
        return;
    }
    let first_diff = expected
        .lines()
        .zip(actual.lines())
        .position(|(e, a)| e != a)
        .unwrap_or_else(|| expected.lines().count().min(actual.lines().count()));
    panic!(
        "the {FLAVOR} build's surface differs from {} at line {}:\n  snapshot: {:?}\n  now:      {:?}\n\
         ({} snapshot lines, {} now). The surface snapshots are a committed baseline: a \
         difference is a surface change, not a stale file.",
        path.display(),
        first_diff + 1,
        expected.lines().nth(first_diff).unwrap_or("<end of snapshot>"),
        actual.lines().nth(first_diff).unwrap_or("<end of output>"),
        expected.lines().count(),
        actual.lines().count(),
    );
}

// ── The web route census and POST allow-list ───────────────────────────────

#[tokio::test]
async fn the_web_route_census_and_post_allow_list_match_the_snapshot() {
    let (census, admitted) = composed_web_surface(&public_host()).await;
    assert_snapshot("web-routes.txt", &render_census(&census));
    assert_snapshot("web-post-allow-list.txt", &(admitted.join("\n") + "\n"));
}

/// The census reads the composed router, not a fixed list: an extension's routes
/// appear in it, and its `POST` in the observed allow-list — so a build that
/// composes extensions over these crates would see them as surface.
#[tokio::test]
async fn the_census_counts_an_extension_route_as_surface() {
    use logos_ext::testing::{StubExtension, STUB_GET_ROUTE, STUB_POST_ROUTE};
    let host = public_host().register(StubExtension::new()).expect("registers");
    let (census, admitted) = composed_web_surface(&host).await;
    let (public, public_admitted) = composed_web_surface(&public_host()).await;
    let added: Vec<&RouteEntry> = census.iter().filter(|r| !public.contains(r)).collect();
    assert_eq!(
        added,
        [
            &RouteEntry { path: STUB_GET_ROUTE.to_string(), methods: vec!["GET"] },
            &RouteEntry { path: STUB_POST_ROUTE.to_string(), methods: vec!["POST"] },
        ]
    );
    let added: Vec<&String> = admitted.iter().filter(|p| !public_admitted.contains(p)).collect();
    assert_eq!(added, [STUB_POST_ROUTE]);
}

// ── MCP tools/list ──────────────────────────────────────────────────────────

#[test]
fn the_mcp_tool_roster_matches_the_snapshot() {
    let (single, federated) = mcp_rosters(&public_host());
    assert_snapshot("mcp-tools-single-root.json", &single);
    assert_snapshot("mcp-tools-federated.json", &federated);
}

// ── CLI help ────────────────────────────────────────────────────────────────

#[test]
fn the_cli_help_matches_the_snapshot() {
    assert_snapshot("logos-help.txt", &help(&["--help"]));
}

// ── The config read-model ───────────────────────────────────────────────────

#[tokio::test]
async fn the_config_read_model_matches_the_snapshot() {
    // The composition root registers the active extensions' config claims before
    // any surface runs (`logos_cli::run`); the snapshot is taken over the same
    // process state — here, no claim: `[wiki]` is ignored and `[chat]` is the
    // core's (S-645's recorded exceptions).
    public_host().register_with_process().expect("the binary's claims are acceptable");
    let dir = configured_project();
    let (status, model) = get_json(&public_host(), dir.path(), "/api/v1/config").await;
    assert_eq!(status, StatusCode::OK);
    assert_snapshot("config-read-model.json", &pretty(&model));
}
